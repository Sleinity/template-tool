import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { loadManifest, repoRoot } from "../fidelity/core.mjs";
import { blendChannel, MATRIX_MODES, validateSourceProfile } from "./source-evidence.mjs";

const manifest = loadManifest();
const profile = JSON.parse(readFileSync(join(repoRoot, "fidelity", "gates", "phase9-compositing-source.json"), "utf8"));
validateSourceProfile(profile, manifest);
assert.deepEqual(MATRIX_MODES, ["NORMAL", "DARKEN", "MULTIPLY", "SCREEN", "OVERLAY", "LIGHTEN"]);
const b = 0.25;
const s = 0.75;
assert.equal(blendChannel(b, s, "NORMAL"), s);
assert.equal(blendChannel(b, s, "DARKEN"), b);
assert.equal(blendChannel(b, s, "MULTIPLY"), 0.1875);
assert.equal(blendChannel(b, s, "SCREEN"), 0.8125);
assert.equal(blendChannel(b, s, "OVERLAY"), 0.375);
assert.equal(blendChannel(b, s, "LIGHTEN"), s);
assert.throws(() => blendChannel(b, s, "UNKNOWN"), /Unrecognized/);
const missing = structuredClone(profile);
missing.fixtures.pop();
assert.throws(() => validateSourceProfile(missing, manifest), /Matrix and Cover only/);
const duplicate = structuredClone(profile);
duplicate.fixtures[1] = structuredClone(duplicate.fixtures[0]);
assert.throws(() => validateSourceProfile(duplicate, manifest), /Matrix and Cover only/);
const wrongHash = structuredClone(profile);
wrongHash.fixtures[0].zipSha256 = "0".repeat(64);
assert.throws(() => validateSourceProfile(wrongHash, manifest));
console.log("Phase 9 source-profile and flat-color blend controls passed.");
